"""Per-collection ``.bib`` generation with LaTeX-safe titles.

Output is deterministic (entries sorted by citation key, fixed field order, no timestamps)
and files are only rewritten when their content changes, so manuscript repositories see
minimal diffs and ``latexmk`` is not re-triggered needlessly.
"""

from __future__ import annotations

import logging
import os
import re
import tempfile
import time
from collections.abc import Iterable, Sequence
from pathlib import Path
from typing import Any

from .models import Collection, Paper
from .storage import normalize_key_component

log = logging.getLogger(__name__)

BIBTEX_DIRNAME = "bibtex"
MASTER_SLUG = "master"
GENERATED_MARKER = "% Generated by JRef"
# Headers written by earlier releases: such files are still ours and may be rewritten without asking.
LEGACY_GENERATED_MARKERS = ("% Generated by JBibManager", "% Generated by bibmanager")

_ROMAN_NUMERAL = re.compile(r"M{0,3}(CM|CD|D?C{0,3})(XC|XL|L?X{0,3})(IX|IV|V?I{0,3})")
_WORD = re.compile(r"[^\W_]+")
_COMMAND = re.compile(r"\\(?:[A-Za-z]+|.)", re.DOTALL)
_DASHES = re.compile(r"\s*[-‐‑‒–—−]+\s*")
_LATEX_SPECIALS = {"&": r"\&", "%": r"\%", "#": r"\#", "_": r"\_"}

_CONTAINER_FIELD = {
    "article": "journal",
    "inproceedings": "booktitle",
    "incollection": "booktitle",
    "inbook": "booktitle",
    "phdthesis": "school",
    "mastersthesis": "school",
    "techreport": "institution",
    "misc": "howpublished",
}
_PUBLISHER_TYPES = frozenset({"book", "inbook", "incollection", "inproceedings", "proceedings", "techreport"})
# Fields rendered from the structured metadata; extra_fields never override them.
_MANAGED_FIELDS = frozenset(
    {"author", "title", "journal", "booktitle", "school", "institution", "howpublished", "publisher", "year",
     "volume", "number", "issue", "pages", "doi", "eprint", "archiveprefix", "abstract", "file", "url"}
)  # fmt: skip
_FIELD_NAME = re.compile(r"[a-z][a-z0-9_\-]*")
_URL_TYPES = frozenset({"misc", "online", "electronic", "www", "webpage"})
_MONTH_MACROS = frozenset({"jan", "feb", "mar", "apr", "may", "jun", "jul", "aug", "sep", "oct", "nov", "dec"})


def _balanced(value: str) -> bool:
    depth = 0
    escaped = False
    for ch in value:
        if escaped:
            escaped = False
        elif ch == "\\":
            escaped = True
        elif ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
            if depth < 0:
                return False
    return depth == 0


# --------------------------------------------------------------------------- LaTeX helpers
def _squash(text: str) -> str:
    return " ".join((text or "").split())


def escape_latex(text: str) -> str:
    """Escape ``& % # _`` outside ``$...$`` math; existing ``\\x`` escapes are preserved."""
    out: list[str] = []
    in_math = False
    i, n = 0, len(text)
    while i < n:
        ch = text[i]
        if ch == "\\" and i + 1 < n:
            out.append(text[i : i + 2])
            i += 2
            continue
        if ch == "$":
            in_math = not in_math
            out.append(ch)
        elif not in_math and ch in _LATEX_SPECIALS:
            out.append(_LATEX_SPECIALS[ch])
        else:
            out.append(ch)
        i += 1
    return "".join(out)


def _needs_protection(word: str, protected: frozenset[str]) -> bool:
    if word in protected:
        return True
    uppers = sum(c.isupper() for c in word)
    if uppers >= 2:  # acronyms and camel case: PINNs, SHM, RVE, FEniCSx, PyTorch
        return True
    if uppers and any(c.isdigit() for c in word):  # 3D, 2D, 6Al
        return True
    if uppers and not word[0].isupper():  # pH, iPhone
        return True
    return _ROMAN_NUMERAL.fullmatch(word) is not None  # I, V, X, ... (multi-letter ones caught above)


def _matching_brace(text: str, start: int) -> int:
    depth = 0
    i = start
    while i < len(text):
        ch = text[i]
        if ch == "\\":
            i += 2
            continue
        if ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
            if depth == 0:
                return i
        i += 1
    return -1


def protect_title(title: str, protected_words: Iterable[str] = ()) -> str:
    """Wrap acronyms, Roman numerals and ``protected_words`` in ``{...}``.

    Existing brace groups, ``$...$`` math and LaTeX commands are copied verbatim, so the
    function is idempotent: ``protect_title(protect_title(t)) == protect_title(t)``.
    """
    protected = frozenset(protected_words)
    out: list[str] = []
    i, n = 0, len(title)
    while i < n:
        ch = title[i]
        if ch == "{":
            end = _matching_brace(title, i)
            if end == -1:  # unbalanced: escape the brace rather than break the .bib file
                out.append(r"\{")
                i += 1
            else:
                out.append(title[i : end + 1])
                i = end + 1
            continue
        if ch == "}":
            out.append(r"\}")
            i += 1
            continue
        if ch == "$":
            end = title.find("$", i + 1)
            end = n - 1 if end == -1 else end
            out.append(title[i : end + 1])
            i = end + 1
            continue
        if ch == "\\":
            m = _COMMAND.match(title, i)
            token = m.group() if m else ch
            out.append(token)
            i += len(token)
            continue
        m = _WORD.match(title, i)
        if m:
            word = m.group()
            out.append("{" + word + "}" if _needs_protection(word, protected) else word)
            i = m.end()
            continue
        out.append(ch)
        i += 1
    return "".join(out)


def format_pages(pages: str) -> str:
    return _DASHES.sub("--", _squash(pages))


# --------------------------------------------------------------------------- rendering
def render_entry(paper: Paper, protected_words: Iterable[str] = (), *, include_abstract: bool = False) -> str:
    meta = paper.meta
    entry_type = (meta.entry_type or "article").lower()
    fields: list[tuple[str, str]] = []

    authors = " and ".join(filter(None, (a.to_bibtex() for a in meta.authors)))
    if authors:
        fields.append(("author", authors))
    if meta.title:
        fields.append(("title", protect_title(escape_latex(_squash(meta.title)), protected_words)))
    container_field = _CONTAINER_FIELD.get(entry_type)
    if meta.journal and container_field:
        fields.append((container_field, escape_latex(_squash(meta.journal))))
    if meta.publisher and entry_type in _PUBLISHER_TYPES:
        fields.append(("publisher", escape_latex(_squash(meta.publisher))))
    if meta.year is not None:
        fields.append(("year", str(meta.year)))
    if meta.volume:
        fields.append(("volume", escape_latex(_squash(meta.volume))))
    if meta.issue:
        fields.append(("number", escape_latex(_squash(meta.issue))))
    if meta.pages:
        fields.append(("pages", format_pages(meta.pages)))
    if meta.doi:
        fields.append(("doi", meta.doi.strip()))
    if meta.arxiv_id:
        fields.append(("eprint", meta.arxiv_id.strip()))
        fields.append(("archiveprefix", "arXiv"))
    if meta.url and entry_type in _URL_TYPES:  # web resources: the URL is the reference
        fields.append(("url", meta.url.strip()))
    if include_abstract and meta.abstract:
        fields.append(("abstract", escape_latex(_squash(meta.abstract))))
    taken = {name for name, _ in fields} | _MANAGED_FIELDS
    for name, value in sorted(meta.extra_fields.items()):  # verbatim pass-through (already LaTeX)
        name = name.lower()
        if name not in taken and _FIELD_NAME.fullmatch(name) and _balanced(value):
            fields.append((name, _squash(value)))

    width = max((len(name) for name, _ in fields), default=0)
    lines = [f"@{entry_type}{{{paper.citation_key},"]
    for name, value in fields:
        if name == "month" and value.lower()[:3] in _MONTH_MACROS and len(value) <= 3:
            lines.append(f"  {name.ljust(width)} = {value.lower()},")  # BibTeX month macro
        else:
            lines.append(f"  {name.ljust(width)} = {{{value}}},")
    lines.append("}")
    body = "\n".join(lines)
    if paper.needs_review:
        body = "% JRef: metadata incomplete or unverified -- needs review\n" + body
    return body


def render_bib(
    papers: Sequence[Paper],
    *,
    label: str,
    protected_words: Iterable[str] = (),
    include_abstract: bool = False,
) -> str:
    protected = tuple(protected_words)
    ordered = sorted(papers, key=lambda p: p.citation_key)
    header = (
        f"{GENERATED_MARKER} -- {label} ({len(ordered)} entries).\n"
        "% Do not edit by hand: this file is rewritten on every library update.\n"
    )
    entries = [render_entry(p, protected, include_abstract=include_abstract) for p in ordered]
    return header + ("\n" + "\n\n".join(entries) + "\n" if entries else "")


def slugify(name: str) -> str:
    """Collection name -> ``.bib`` file stem (``"Viscoelastic fracture"`` -> ``viscoelastic_fracture``)."""
    return normalize_key_component(name) or "collection"


# --------------------------------------------------------------------------- file I/O
def write_text_atomic(path: Path, content: str, *, retries: int = 5) -> bool:
    """Write via temp file + ``os.replace``. Returns False (and does nothing) if unchanged."""
    path = Path(path)
    try:
        if path.read_text(encoding="utf-8") == content:
            return False
    except (FileNotFoundError, UnicodeDecodeError):
        pass
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp_name = tempfile.mkstemp(prefix=f".{path.name}.", suffix=".tmp", dir=path.parent)
    tmp = Path(tmp_name)
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(content)
        for attempt in range(retries):
            try:
                os.replace(tmp, path)
                break
            except PermissionError:  # Windows: file briefly locked by an editor / sync client
                if attempt == retries - 1:
                    raise
                time.sleep(0.1 * (attempt + 1))
    finally:
        tmp.unlink(missing_ok=True)
    return True


def is_generated_bib(path: Path) -> bool:
    try:
        with Path(path).open(encoding="utf-8") as fh:
            return fh.readline().startswith((GENERATED_MARKER, *LEGACY_GENERATED_MARKERS))
    except (FileNotFoundError, UnicodeDecodeError):
        return False


class BibtexManager:
    """Owns ``<library_root>/bibtex``; mirrors collections to optional external ``.bib`` targets."""

    def __init__(
        self, bibtex_dir: Path, protected_words: Iterable[str] = (), *, include_abstract: bool = False
    ) -> None:
        self.bibtex_dir = Path(bibtex_dir)
        self.protected_words = tuple(protected_words)
        self.include_abstract = include_abstract

    def collection_path(self, slug: str) -> Path:
        return self.bibtex_dir / f"{slug}.bib"

    @property
    def master_path(self) -> Path:
        return self.collection_path(MASTER_SLUG)

    def render(self, papers: Sequence[Paper], *, label: str) -> str:
        return render_bib(
            papers, label=label, protected_words=self.protected_words, include_abstract=self.include_abstract
        )

    def targets_for(self, collection: Collection) -> list[Path]:
        targets = [self.collection_path(collection.slug)]
        if collection.bib_export_path:
            external = Path(collection.bib_export_path).expanduser()
            if not external.parent.is_dir():
                log.warning("External .bib folder missing, skipped: %s", external.parent)
            elif external.resolve() != targets[0].resolve():
                targets.append(external)
        return targets

    def write_collection(self, collection: Collection, papers: Sequence[Paper]) -> list[Path]:
        content = self.render(papers, label=f'collection "{collection.name}"')
        targets = self.targets_for(collection)
        for target in targets:
            if write_text_atomic(target, content):
                log.info("Wrote %s", target)
        return targets

    def write_master(self, papers: Sequence[Paper]) -> Path:
        write_text_atomic(self.master_path, self.render(papers, label="master library"))
        return self.master_path

    def remove_collection_file(self, slug: str) -> None:
        if slug != MASTER_SLUG:
            self.collection_path(slug).unlink(missing_ok=True)

    @staticmethod
    def parse_file(path: Path) -> Any:
        """Parse a ``.bib`` with bibtexparser v2 (used for validation and future imports)."""
        import bibtexparser  # imported lazily: only the desktop test-suite needs it (not bundled on Android)

        return bibtexparser.parse_string(Path(path).read_text(encoding="utf-8"))
