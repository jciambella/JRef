_WHOLE_LIBRARY_NAMES = frozenset({"library", "my library", "all documents", "master", "mendeley", "references"})


def folder_name_for(options: MendeleyImportOptions, bib_path: Path) -> str:
    """Folder that receives every entry of ``bib_path`` ("" = none)."""
    for path, name in options.bib_folders.items():
        if Path(path) == Path(bib_path):
            return " ".join(name.split())
    return Path(bib_path).stem if options.bib_as_folder else ""


def suggest_bib_folder(bib_path: Path, file_count: int) -> bool:
    """Default for the per-file "use as folder" choice: several files are normally Mendeley's one-file-per-
    collection export, except a whole-library file (``library.bib``)."""
    return file_count > 1 and Path(bib_path).stem.casefold() not in _WHOLE_LIBRARY_NAMES


@dataclass(slots=True)
class BibFileSummary:
    path: Path
    entries: int = 0
    with_groups: int = 0  # entries carrying mendeley-groups
    with_files: int = 0  # entries with a file field
    groups: list[str] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)
    error: str = ""


def summarize_bib_file(path: Path) -> BibFileSummary:
    """Quick look at a .bib export (no file-system checks): what an import would find in it."""
    summary = BibFileSummary(Path(path))
    try:
        parsed = parse_bibtex(read_bib_file(Path(path)))
    except OSError as exc:
        summary.error = str(exc)
        return summary
    groups: dict[str, None] = {}
    for entry in parsed.entries:
        summary.entries += 1
        if entry.fields.get("mendeley-groups", "").strip():
            summary.with_groups += 1
            groups.update(dict.fromkeys(_list(entry.fields["mendeley-groups"])))
        if entry.fields.get("file", "").strip():
            summary.with_files += 1
    summary.groups = list(groups)
    summary.warnings = parsed.warnings
    return summary


def read_bib_file(path: Path) -> str:
    data = Path(path).read_bytes()
    for encoding in ("utf-8-sig", "cp1252", "latin-1"):
        try:
            return data.decode(encoding)
        except UnicodeDecodeError:
            continue
    return data.decode("utf-8", errors="replace")  # pragma: no cover - latin-1 always succeeds


def plan_import(options: MendeleyImportOptions) -> MendeleyImportPlan:
    """Parse the .bib file(s), merge duplicates across files, locate every PDF. No SQLite, no Qt."""
    plan = MendeleyImportPlan()
    by_key: dict[str, ReferenceCandidate] = {}
    for bib_path in options.bib_paths:
        bib_path = Path(bib_path)
        parsed = parse_bibtex(read_bib_file(bib_path))
        plan.warnings += [f"{bib_path.name}: {w}" for w in parsed.warnings]
        folder_name = folder_name_for(options, bib_path)
        if folder_name:
            plan.bib_folders[folder_name] = bib_path
        for entry in parsed.entries:
            if not entry.key and not entry.fields:
                continue
            cand = entry_to_candidate(entry, import_notes=options.import_notes)
            if not options.import_groups:
                cand.folders = []
            if folder_name:
                cand.folders.append((folder_name,))
            ident = (cand.key or f"#{len(by_key)}").casefold()
            if ident in by_key:  # same entry exported in several per-folder files
                previous = by_key[ident]
                previous.folders = list(dict.fromkeys([*previous.folders, *cand.folders]))
                continue
            by_key[ident] = cand
    plan.candidates = list(by_key.values())

    if options.database is not None:
        try:
            plan.database_matches = merge_database_info(plan.candidates, read_mendeley_database(options.database))
            if not options.import_groups:
                for cand in plan.candidates:
                    cand.folders = []
        except MendeleyDatabaseError as exc:
            plan.warnings.append(str(exc))

    # Recorded paths that no longer exist are looked up by file name (indexed lazily, only if needed).
    roots = [options.pdf_folder] if options.pdf_folder else sorted({Path(p).parent for p in options.bib_paths})
    locator = PdfLocator(roots)
    for cand in plan.candidates:
        recorded, cand.extra_files = cand.extra_files, []
        for raw in recorded:
            found = locator.locate(raw)
            if found is not None and found.suffix.lower() == ".pdf" and cand.pdf_path is None:
                cand.pdf_path = found
            elif found is not None:
                cand.extra_files.append(str(found))
            else:
                cand.missing_files.append(raw)
    return plan


def summarize(plan: MendeleyImportPlan) -> str:
    total = len(plan.candidates)
    no_file = sum(1 for c in plan.candidates if c.pdf_path is None and not c.missing_files)
    return (
        f"{total} references: {plan.with_pdf} with PDF, {len(plan.missing_pdf)} whose PDF was not found, "
        f"{no_file} without attachment"
    )


