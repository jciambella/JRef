# =========================================================================== BibTeX tokenizer
_MONTHS = {
    "jan": "jan", "feb": "feb", "mar": "mar", "apr": "apr", "may": "may", "jun": "jun",
    "jul": "jul", "aug": "aug", "sep": "sep", "oct": "oct", "nov": "nov", "dec": "dec",
}  # fmt: skip
_IDENT = re.compile(r"[^\s\"#%'(),={}]+")


@dataclass(slots=True)
class BibEntry:
    entry_type: str
    key: str
    fields: dict[str, str]  # lower-case name -> raw value (outer braces/quotes removed, LaTeX kept)
    line: int = 0


@dataclass(slots=True)
class BibParseResult:
    entries: list[BibEntry] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)


class _Reader:
    def __init__(self, text: str) -> None:
        self.text = text
        self.pos = 0
        self.n = len(text)
        self._line_pos = 0  # incremental line counting (entries are visited in order)
        self._line_no = 1

    def line(self, pos: int | None = None) -> int:
        pos = self.pos if pos is None else pos
        if pos < self._line_pos:
            self._line_pos, self._line_no = 0, 1
        self._line_no += self.text.count("\n", self._line_pos, pos)
        self._line_pos = pos
        return self._line_no

    def skip_ws(self) -> None:
        while self.pos < self.n and self.text[self.pos].isspace():
            self.pos += 1

    def peek(self) -> str:
        return self.text[self.pos] if self.pos < self.n else ""

    _BRACES = {("{", "}"): re.compile(r"[{}]"), ("(", ")"): re.compile(r"[()]")}

    def balanced(self, open_ch: str, close_ch: str) -> str:
        """Read ``{...}`` (or ``(...)``) starting at the opening delimiter; BibTeX counts every brace."""
        assert self.text[self.pos] == open_ch
        depth = 0
        start = self.pos + 1
        for match in self._BRACES[(open_ch, close_ch)].finditer(self.text, self.pos):
            depth += 1 if match.group() == open_ch else -1
            if depth == 0:
                self.pos = match.end()
                return self.text[start : match.start()]
        self.pos = self.n
        raise ValueError("unbalanced braces")

    def quoted(self) -> str:
        assert self.text[self.pos] == '"'
        self.pos += 1
        start, depth = self.pos, 0
        while self.pos < self.n:
            ch = self.text[self.pos]
            if ch == "{":
                depth += 1
            elif ch == "}":
                depth -= 1
            elif ch == '"' and depth == 0:
                self.pos += 1
                return self.text[start : self.pos - 1]
            self.pos += 1
        raise ValueError("unterminated quoted value")


def parse_bibtex(text: str) -> BibParseResult:
    """Tolerant BibTeX parser: text between entries (Mendeley's header) is ignored, a malformed entry is
    skipped with a warning, ``@string`` macros and ``#`` concatenation are honoured."""
    result = BibParseResult()
    macros: dict[str, str] = dict(_MONTHS)
    reader = _Reader(text)
    while True:
        at = text.find("@", reader.pos)
        if at < 0:
            break
        reader.pos = at + 1
        match = re.compile(r"[A-Za-z]+").match(text, reader.pos)
        if not match:
            continue
        entry_type = match.group(0).lower()
        reader.pos = match.end()
        reader.skip_ws()
        opener = reader.peek()
        if opener not in "{(":
            continue
        closer = "}" if opener == "{" else ")"
        start_line = reader.line(at)
        try:
            if entry_type in ("comment", "preamble"):
                reader.balanced(opener, closer)
                continue
            if entry_type == "string":
                body = reader.balanced(opener, closer)
                name, _, value = body.partition("=")
                sub = _Reader(value.strip())
                macros[name.strip().lower()] = _read_value(sub, macros) if sub.n else ""
                continue
            entry = _read_entry(reader, entry_type, closer, macros)
            entry.line = start_line
            result.entries.append(entry)
        except ValueError as exc:
            result.warnings.append(f"line {start_line}: skipped malformed @{entry_type} entry ({exc})")
            nxt = text.find("\n@", at + 1)
            reader.pos = nxt + 1 if nxt >= 0 else reader.n
    return result


def _read_entry(reader: _Reader, entry_type: str, closer: str, macros: dict[str, str]) -> BibEntry:
    reader.pos += 1  # opening delimiter
    reader.skip_ws()
    key_end = reader.pos
    while key_end < reader.n and reader.text[key_end] not in ",\n" + closer:
        key_end += 1
    key = reader.text[reader.pos : key_end].strip()
    reader.pos = key_end
    fields: dict[str, str] = {}
    while True:
        reader.skip_ws()
        ch = reader.peek()
        if ch == ",":
            reader.pos += 1
            continue
        if ch == closer:
            reader.pos += 1
            break
        if not ch:
            raise ValueError("unexpected end of file")
        if ch == "@":
            raise ValueError("missing closing brace")
        name_match = _IDENT.match(reader.text, reader.pos)
        if not name_match:
            raise ValueError(f"unexpected character {ch!r}")
        name = name_match.group(0).lower()
        reader.pos = name_match.end()
        reader.skip_ws()
        if reader.peek() != "=":
            raise ValueError(f"expected '=' after field {name!r}")
        reader.pos += 1
        fields[name] = _read_value(reader, macros)
    return BibEntry(entry_type, key, fields)


def _read_value(reader: _Reader, macros: dict[str, str]) -> str:
    parts: list[str] = []
    while True:
        reader.skip_ws()
        ch = reader.peek()
        if ch == "{":
            parts.append(reader.balanced("{", "}"))
        elif ch == '"':
            parts.append(reader.quoted())
        else:
            ident = _IDENT.match(reader.text, reader.pos)
            if not ident:
                raise ValueError("missing field value")
            reader.pos = ident.end()
            token = ident.group(0)
            parts.append(token if token.isdigit() else macros.get(token.lower(), token))
        reader.skip_ws()
        if reader.peek() == "#":
            reader.pos += 1
            continue
        return "".join(parts)


# =========================================================================== LaTeX -> Unicode
_ACCENTS = {
    "'": "\u0301", "`": "\u0300", "^": "\u0302", '"': "\u0308", "~": "\u0303", "=": "\u0304", ".": "\u0307",
    "u": "\u0306", "v": "\u030c", "H": "\u030b", "c": "\u0327", "k": "\u0328", "r": "\u030a", "d": "\u0323",
    "b": "\u0331", "t": "\u0361",
}  # fmt: skip
_SYMBOLS = {
    "i": "ı", "j": "ȷ", "o": "ø", "O": "Ø", "l": "ł", "L": "Ł", "ss": "ß", "SS": "SS", "aa": "å", "AA": "Å",
    "ae": "æ", "AE": "Æ", "oe": "œ", "OE": "Œ", "dh": "ð", "DH": "Ð", "th": "þ", "TH": "Þ", "ng": "ŋ", "NG": "Ŋ",
    "textless": "<", "textgreater": ">", "textasciitilde": "~", "textasciicircum": "^", "textendash": "–",
    "textemdash": "—", "textquoteright": "’", "textquoteleft": "‘", "textquotedblleft": "“",
    "textquotedblright": "”", "textregistered": "®", "texttrademark": "™", "textcopyright": "©",
    "textdegree": "°", "textperiodcentered": "·", "textbullet": "•", "textbar": "|", "textunderscore": "_",
    "textsterling": "£", "texteuro": "€", "euro": "€", "S": "§", "P": "¶", "dag": "†", "ddag": "‡",
    "ldots": "…", "dots": "…", "textellipsis": "…", "textmu": "µ", "textperthousand": "‰",
}  # fmt: skip
_TEXT_ESCAPES = {"&": "&", "%": "%", "#": "#", "_": "_"}
_MATH_TO_TEXT = {r"\backslash": "\\"}  # Mendeley's spelling of a literal backslash; other math stays math
_LETTERS = re.compile(r"[A-Za-z]+")


def latex_to_unicode(value: str, *, text: bool = True) -> str:
    """Decode the LaTeX escaping of Mendeley/JabRef/BibTeX values into the plain text bibmanager stores.

    Accents and symbols become Unicode, case-protection braces are dropped (bibmanager re-protects titles
    on export), ``$...$`` math is kept verbatim. Mendeley escapes a math ``$`` as ``{\\$}``: an even number
    of them is decoded back to math, an odd one stays a literal ``\\$``. ``text=False`` (file paths) keeps
    ``~`` and dashes as they are.
    """
    out: list[str] = []
    dollars_are_math = value.count(r"\$") % 2 == 0
    i, n = 0, len(value)
    while i < n:
        ch = value[i]
        if ch == "$":
            end = value.find("$", i + 1)
            if end < 0:
                out.append(ch)
                i += 1
                continue
            body = value[i + 1 : end]
            out.append(_MATH_TO_TEXT.get(body.strip(), f"${body}$"))
            i = end + 1
        elif ch == "\\" and i + 1 < n:
            consumed, produced = _decode_command(value, i, dollars_are_math, text)
            out.append(produced)
            i = consumed
        elif ch in "{}":
            i += 1
        elif text and ch == "~":
            out.append(" ")
            i += 1
        else:
            out.append(ch)
            i += 1
    result = unicodedata.normalize("NFC", "".join(out))
    if text:
        result = result.replace("---", "—").replace("--", "–")
        result = " ".join(result.split())
    return result


def _group_or_char(value: str, i: int) -> tuple[int, str]:
    """Accent argument: ``{x}``, ``{\\i}``, ``x`` (after optional spaces); returns (next index, base text)."""
    n = len(value)
    while i < n and value[i] == " ":
        i += 1
    if i >= n:
        return i, ""
    if value[i] == "{":
        depth, j = 0, i
        while j < n:
            if value[j] == "{":
                depth += 1
            elif value[j] == "}":
                depth -= 1
                if depth == 0:
                    break
            j += 1
        inner = value[i + 1 : j].strip()
        if inner in (r"\i", r"\j"):
            inner = inner[1]
        return j + 1, inner
    if value[i] == "\\" and i + 1 < n and value[i + 1] in "ij" and not value[i + 2 : i + 3].isalpha():
        return i + 2, value[i + 1]
    return i + 1, value[i]


def _decode_command(value: str, i: int, dollars_are_math: bool, text: bool) -> tuple[int, str]:
    nxt = value[i + 1]
    if nxt in _ACCENTS and not nxt.isalpha():
        j, base = _group_or_char(value, i + 2)
        if not base:  # \~{} or \^{} -> the character itself
            return j, nxt
        return j, base[0] + _ACCENTS[nxt] + base[1:]
    if nxt in _TEXT_ESCAPES:
        return i + 2, _TEXT_ESCAPES[nxt]
    if nxt == "$":
        return i + 2, "$" if dollars_are_math else r"\$"
    if nxt in "{}":
        return i + 2, "\\" + nxt  # literal brace stays escaped (balanced output)
    if nxt == "\\":
        return i + 2, " "  # line break
    if nxt == " ":
        return i + 2, " "
    letters = _LETTERS.match(value, i + 1)
    if not letters:
        return i + 2, value[i : i + 2]  # \: \, \; ... kept verbatim
    name = letters.group(0)
    j = letters.end()
    if name in _ACCENTS and len(name) == 1 and (j < len(value) and value[j] in "{ "):
        k, base = _group_or_char(value, j)
        if base:
            return k, base[0] + _ACCENTS[name] + base[1:]
    if name in _SYMBOLS:
        if value[j : j + 2] == "{}":
            j += 2
        elif j < len(value) and value[j] == " ":
            j += 1
        return j, _SYMBOLS[name]
    if j < len(value) and value[j] == "{":  # unknown command with an argument (\emph{...}): keep both
        end, _ = _group_or_char(value, j)
        inner = value[j + 1 : end - 1]
        return end, "\\" + name + "{" + latex_to_unicode(inner, text=text) + "}"
    rest = value[j:].lstrip("}")
    if rest[:1].isalpha() or rest[:1].isspace():  # {\TeX}book -> \TeX{}book: the dropped brace ended the name
        return j, "\\" + name + "{}"
    return j, "\\" + name  # unknown command without argument (\LaTeX ...) is kept verbatim


_HTML_TAG = re.compile(r"<[^>]+>")


def html_to_text(text: str) -> str:
    """Mendeley notes may contain simple HTML."""
    text = re.sub(r"(?i)<br\s*/?>|</p>", "\n", text)
    return html.unescape(_HTML_TAG.sub("", text)).strip()


# =========================================================================== names, years, files
def _split_top_level(value: str, separator: re.Pattern[str]) -> list[str]:
    parts, depth, last = [], 0, 0
    i = 0
    while i < len(value):
        ch = value[i]
        if ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
        elif depth == 0:
            m = separator.match(value, i)
            if m:
                parts.append(value[last:i])
                last = i = m.end()
                continue
        i += 1
    parts.append(value[last:])
    return [p.strip() for p in parts if p.strip()]


_AND = re.compile(r"\s+and\s+", re.IGNORECASE)
_COMMA = re.compile(r",")
_VON = re.compile(r"[a-z]")


def parse_bibtex_authors(raw: str) -> list[Author]:
    """BibTeX name list (``Last, First and von Last, Jr, First and {Corporate Name}``), LaTeX decoded."""
    authors: list[Author] = []
    for chunk in _split_top_level(raw, _AND):
        if chunk.startswith("{") and chunk.endswith("}") and _split_top_level(chunk[1:-1], _COMMA) == [chunk[1:-1]]:
            authors.append(Author(literal=latex_to_unicode(chunk)))
            continue
        pieces = [latex_to_unicode(p) for p in _split_top_level(chunk, _COMMA)]
        if len(pieces) >= 3:
            authors.append(Author(family=pieces[0], suffix=pieces[1], given=", ".join(pieces[2:])))
        elif len(pieces) == 2:
            authors.append(Author(family=pieces[0], given=pieces[1]))
        elif pieces:
            words = pieces[0].split()
            if len(words) == 1:
                authors.append(Author(family=words[0]))
                continue
            # "First von Last": the family name starts at the first lower-case word (von part), else last word
            start = next((k for k, w in enumerate(words[:-1]) if k and _VON.match(w)), len(words) - 1)
            authors.append(Author(family=" ".join(words[start:]), given=" ".join(words[:start])))
    return [a for a in authors if a.key_name]


def parse_year(raw: str) -> int | None:
    match = re.search(r"\b(1[0-9]{3}|2[0-9]{3})\b", raw or "")
    return int(match.group(1)) if match else None


def parse_file_field(raw: str) -> list[str]:
    """``:C$\\backslash$:/x/a.pdf:pdf;:home/me/b.pdf:pdf`` -> ``["C:/x/a.pdf", "/home/me/b.pdf"]`` (PDFs first)."""
    value = raw.replace(r"$\backslash$", "\\").replace(r"{\textbackslash}", "\\")
    files: list[tuple[str, str]] = []
    for attachment in re.split(r"(?<!\\);", value):
        attachment = attachment.strip()
        if not attachment:
            continue
        parts = re.split(r"(?<!\\):", attachment)
        if len(parts) >= 3:
            description, path, kind = parts[0], ":".join(parts[1:-1]), parts[-1]
        elif len(parts) == 2:
            description, path, kind = "", parts[0] or parts[1], ""
        else:
            description, path, kind = "", parts[0], ""
        del description
        protected = path.replace("\\\\", "\x02").replace("\\:", "\x00").replace("\\;", "\x01")
        path = latex_to_unicode(protected, text=False)
        path = path.replace("\x00", ":").replace("\x01", ";").replace("\x02", "\\").strip()
        if not path:
            continue
        if not _is_absolute_any(path) and not path.startswith(("./", "../")):
            first = PurePosixPath(path).parts[0] if PurePosixPath(path).parts else ""
            if first in ("home", "Users", "Volumes", "media", "mnt", "opt", "srv", "tmp", "var", "net", "run"):
                path = "/" + path  # Mendeley drops the leading '/' of POSIX paths
        files.append((path, kind.strip().lower()))
    files.sort(key=lambda item: 0 if item[1] == "pdf" or item[0].lower().endswith(".pdf") else 1)
    return list(dict.fromkeys(path for path, _ in files))


def _is_absolute_any(path: str) -> bool:
    return PurePosixPath(path).is_absolute() or PureWindowsPath(path).is_absolute() or path.startswith("\\\\")


class PdfLocator:
    """Find the PDF a ``file`` field points to, even after the Mendeley folder moved (other drive, other
    user name, synced to another machine): exact path first, then the file name inside ``search_root``."""

    def __init__(self, search_roots: Iterable[Path] = ()) -> None:
        self.search_roots = [Path(r) for r in search_roots if r and Path(r).is_dir()]
        self._index: dict[str, list[Path]] | None = None

    def _build_index(self) -> dict[str, list[Path]]:
        index: dict[str, list[Path]] = {}
        for root in self.search_roots:
            for dirpath, _dirnames, filenames in os.walk(root):
                for name in filenames:
                    index.setdefault(unicodedata.normalize("NFC", name).casefold(), []).append(Path(dirpath, name))
        return index

    def locate(self, recorded: str) -> Path | None:
        direct = Path(recorded)
        try:
            if direct.is_absolute() and direct.is_file():
                return direct
        except OSError:
            pass
        name = PureWindowsPath(recorded).name if "\\" in recorded else PurePosixPath(recorded).name
        if not name or not self.search_roots:
            return None
        if self._index is None:
            self._index = self._build_index()
        matches = self._index.get(unicodedata.normalize("NFC", name).casefold(), [])
        if len(matches) <= 1:
            return matches[0] if matches else None
        wanted = [p.casefold() for p in re.split(r"[\\/]+", recorded) if p]

        def common_suffix(path: Path) -> int:
            parts = [p.casefold() for p in path.parts]
            k = 0
            while k < min(len(parts), len(wanted)) and parts[-1 - k] == wanted[-1 - k]:
                k += 1
            return k

        return max(matches, key=common_suffix)


def default_mendeley_pdf_folder() -> Path | None:
    """Mendeley Desktop's default "Organize my files" folder, if it exists."""
    candidate = Path.home() / "Documents" / "Mendeley Desktop"
    return candidate if candidate.is_dir() else None


# =========================================================================== entry -> candidate
_CONTAINER_BY_TYPE = {
    "article": "journal", "inproceedings": "booktitle", "conference": "booktitle", "incollection": "booktitle",
    "inbook": "booktitle", "phdthesis": "school", "mastersthesis": "school", "thesis": "school",
    "techreport": "institution", "report": "institution", "misc": "howpublished",
}  # fmt: skip
_CONTAINER_FIELDS = ("journal", "booktitle", "school", "institution", "howpublished")
# Further fields worth keeping in the generated .bib, stored verbatim (already LaTeX).
PASSTHROUGH_FIELDS = frozenset(
    {"editor", "address", "edition", "series", "chapter", "organization", "month", "note", "type",
     "eprinttype", "primaryclass", "language", "urldate"}
)  # fmt: skip
_TYPE_ALIASES = {"conference": "inproceedings", "thesis": "phdthesis", "report": "techreport", "electronic": "misc"}


def _list(raw: str) -> list[str]:
    return [item for item in (latex_to_unicode(p) for p in re.split(r"[,;]", raw or "")) if item]


def entry_to_candidate(entry: BibEntry, *, import_notes: bool = True) -> ReferenceCandidate:
    f = entry.fields
    entry_type = _TYPE_ALIASES.get(entry.entry_type, entry.entry_type) or "article"
    extra: dict[str, str] = {}
    container = ""
    preferred = _CONTAINER_BY_TYPE.get(entry.entry_type) or _CONTAINER_BY_TYPE.get(entry_type)
    if preferred:
        source = preferred if f.get(preferred) else next((c for c in _CONTAINER_FIELDS if f.get(c)), "")
        if source:
            container = latex_to_unicode(f[source])
        for name in _CONTAINER_FIELDS:
            if name != source and f.get(name):
                extra[name] = f[name].strip()
    else:
        for name in _CONTAINER_FIELDS:
            if f.get(name):
                extra[name] = f[name].strip()
    for name in PASSTHROUGH_FIELDS:
        if f.get(name, "").strip():
            extra[name] = f[name].strip()

    arxiv = f.get("arxivid", "") or (
        f.get("eprint", "") if f.get("archiveprefix", "arxiv").lower() == "arxiv" or "arxivid" in f else ""
    )
    url = latex_to_unicode(f.get("url", ""), text=False).split()
    meta = PaperMetadata(
        title=latex_to_unicode(f.get("title", "")),
        authors=parse_bibtex_authors(f.get("author", "")),
        year=parse_year(f.get("year", "")),
        journal=container,
        volume=latex_to_unicode(f.get("volume", "")),
        issue=latex_to_unicode(f.get("number", "") or f.get("issue", "")),
        pages=latex_to_unicode(f.get("pages", ""), text=False).replace("--", "-").replace("—", "-").strip(),
        publisher=latex_to_unicode(f.get("publisher", "")),
        doi=latex_to_unicode(f.get("doi", ""), text=False).strip(),
        arxiv_id=latex_to_unicode(arxiv, text=False).strip(),
        entry_type=entry_type,
        abstract=latex_to_unicode(f.get("abstract", "")),
        url=url[0] if url else "",
        isbn=latex_to_unicode(f.get("isbn", "")),
        issn=latex_to_unicode(f.get("issn", "")),
        pmid=latex_to_unicode(f.get("pmid", "")),
        keywords="; ".join(dict.fromkeys(_list(f.get("keywords", "")))),
        extra_fields=extra,
    )
    groups: list[tuple[str, ...]] = [(g,) for g in dict.fromkeys(_list(f.get("mendeley-groups", "")))]
    notes = html_to_text(latex_to_unicode(f.get("annote", ""), text=False)) if import_notes else ""
    files = parse_file_field(f.get("file", "")) if f.get("file") else []
    return ReferenceCandidate(
        key=entry.key,
        metadata=meta,
        folders=groups,
        tags="; ".join(dict.fromkeys(_list(f.get("mendeley-tags", "")))) if import_notes else "",
        notes=notes,
        extra_files=files,  # resolved by plan_import(); unresolved ones move to missing_files
    )


