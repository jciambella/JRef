"""Import a Mendeley Desktop library *in place* from its BibTeX export (and, optionally, its database).

Mendeley Desktop writes BibTeX like::

    Automatically generated by Mendeley Desktop 1.19.8
    ...
    @article{Ciambella2025,
    abstract = {...},
    author = {Ciambella, Jacopo and Lancioni, Giovanni},
    file = {:C$\\backslash$:/Users/me/Mendeley Desktop/Ciambella, Lancioni - 2025 - A title.pdf:pdf},
    mendeley-groups = {Hydrogels,Fracture},
    title = {{A title with {\\&} and {\\'{e}}}},
    year = {2025}
    }

The ``file`` field uses the JabRef convention ``description:path:type`` (``;``-separated, ``\\:`` escapes the
colon) on top of Mendeley's LaTeX escaping (``$\\backslash$``, ``{\\_}``, ``{\\'{e}}`` ...). Everything here is
pure Python: parsing, LaTeX decoding, locating the PDFs (also after the folder was moved or synced to another
machine) and reading the unencrypted Mendeley SQLite database for favourite/read flags and folder nesting.
The database of Mendeley Desktop >= 1.19.5 is encrypted; that is detected and reported, never worked around.

The resulting :class:`~bibmanager.core.library.ReferenceCandidate` objects are committed by
``Library.prepare_reference`` (worker thread) and ``Library.commit_reference`` (GUI thread).
"""

