def bib_entries(path: Path) -> dict[str, dict[str, str]]:
    library = bibtexparser.parse_string(path.read_text(encoding="utf-8"))
    assert not library.failed_blocks, library.failed_blocks
    return {e.key: {f.key.lower(): str(f.value) for f in e.fields} for e in library.entries}


def meta(*surnames: str, year: int | None = 2023, title: str = "A title") -> PaperMetadata:
    return PaperMetadata(title=title, authors=[Author(s, "A.") for s in surnames], year=year, journal="J")


