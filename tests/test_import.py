def write_pdf(path: Path, text: str = "x") -> Path:
    import pymupdf

    path.parent.mkdir(parents=True, exist_ok=True)
    doc = pymupdf.open()
    doc.new_page().insert_text((72, 72), f"{text} {path.name}")
    doc.save(path)
    doc.close()
    return path


