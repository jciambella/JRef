def test_latex_decoding_of_mendeley_escapes() -> None:
    assert latex_to_unicode(r"{{Garc{\'{i}}a {\&} M{\"{u}}ller}}") == "García & Müller"
    assert latex_to_unicode(r"{\$}$\backslash$alpha{\$} and {\%}") == r"$\alpha$ and %"  # Mendeley's math
    assert latex_to_unicode(r"costs {\$}5") == r"costs \$5"  # a lone dollar stays literal
    assert (
        latex_to_unicode(r"x {\textless} y, S{\o}rensen, {\v{S}}koda, \c{c}, {\ss}") == "x < y, Sørensen, Škoda, ç, ß"
    )
    assert latex_to_unicode(r"The {\TeX}book, \emph{in situ}") == r"The \TeX{}book, \emph{in situ}"
    assert latex_to_unicode(r"stress--strain --- done") == "stress–strain — done"
    assert latex_to_unicode(r"keep $x^{2}$ math") == "keep $x^{2}$ math"


