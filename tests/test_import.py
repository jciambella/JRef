def import_all(library: Library, options: MendeleyImportOptions) -> dict[str, IngestStatus]:
    """What the GUI controller does, synchronously."""
    statuses: dict[str, IngestStatus] = {}
    with library.bulk_update():
        for cand in plan_import(options).candidates:
            cand = library.prepare_reference(cand, index_fulltext=options.index_fulltext)
            folder_ids = [library.ensure_collection_path(path) for path in cand.folders]
            result = library.commit_reference(
                cand, file_mode=options.file_mode, keep_key=options.keep_keys, folder_ids=folder_ids
            )
            statuses[result.paper.citation_key] = result.status
    return statuses


def test_import_in_place_keeps_files_keys_and_folders(library: Library, mendeley_export: tuple[Path, Path]) -> None:
    bib, folder = mendeley_export
    before = sorted(p.relative_to(folder) for p in folder.rglob("*"))
    options = MendeleyImportOptions(bib_paths=[bib], pdf_folder=folder)
    assert set(import_all(library, options).values()) == {IngestStatus.IMPORTED}
    assert sorted(p.relative_to(folder) for p in folder.rglob("*")) == before  # Mendeley folder untouched
    assert list((library.root / "pdfs").rglob("*.pdf")) == []

    paper = library.db.get_paper_by_citation_key("Ciambella2025")
    assert paper is not None and paper.pdf_linked and not paper.pdf_managed
    assert library.pdf_path(paper) == folder / "Hydrogels" / "Ciambella et al. - 2025 - Hydrogel fracture.pdf"
    assert Path(paper.relative_pdf_path or "").is_absolute()  # outside the library root
    assert [c.name for c in library.collections_of(paper.id)] == ["Hydrogels", "Thesis"]
    knuth = library.db.get_paper_by_citation_key("Knuth1984")
    assert knuth is not None and not knuth.has_pdf and knuth.sha256 is None

    hydro = library.db.list_collections()[0]
    entries = bib_entries(library.bib.collection_path(hydro.slug))
    assert list(entries) == ["Ciambella2025"]
    master = bib_entries(library.bib.master_path)
    assert set(master) == {"Ciambella2025", "Smith2020a", "Knuth1984", "Web2019"}
    assert master["Smith2020a"]["editor"] == "Doe, Jane" and master["Smith2020a"]["address"] == "Rome"
    assert master["Smith2020a"]["booktitle"] == r"Proc. of Çeşme Conference"
    assert master["Ciambella2025"]["month"] in ("jan", "January")  # written as the BibTeX macro
    assert re.search(r"month\s*= jan,", library.bib.master_path.read_text(encoding="utf-8"))
    assert master["Web2019"]["url"] == "https://example.org/data"
    assert [hit.paper_id for hit in library.search_fulltext("hydrogel")] == [paper.id]  # full text indexed

    # Re-running the import adds nothing: PDFs match by hash, file-less entries by key + title.
    assert import_all(library, options) == {
        "Ciambella2025": IngestStatus.DUPLICATE_HASH,
        "Smith2020a": IngestStatus.DUPLICATE_HASH,
        "Knuth1984": IngestStatus.DUPLICATE_KEY,
        "Web2019": IngestStatus.DUPLICATE_KEY,
    }
    assert library.db.count_papers() == 4


