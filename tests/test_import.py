def test_keys_are_unique_case_insensitively_and_legacy_keys_can_be_upgraded(
    library: Library, make_pdf: Callable[..., Path]
) -> None:
    first = library.ingest_pdf(make_pdf(), metadata=meta("Anand")).paper
    library.db.update_paper(first.id, citation_key="anand_2023", relative_pdf_path="pdfs/2023/anand_2023.pdf")
    os.replace(library.root / "pdfs/2023/Anand_2023.pdf", library.root / "pdfs/2023/anand_2023.pdf")
    second = library.ingest_pdf(make_pdf(), metadata=meta("Anand")).paper
