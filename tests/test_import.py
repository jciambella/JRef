def make_mendeley_db(path: Path) -> Path:
    with sqlite3.connect(path) as conn:
        conn.executescript(
            """
            CREATE TABLE Documents (id INTEGER PRIMARY KEY, citationKey TEXT, doi TEXT, title TEXT,
                favourite TEXT, read TEXT, note TEXT, deletionPending TEXT);
            CREATE TABLE Folders (id INTEGER PRIMARY KEY, name TEXT, parentId INTEGER);
            CREATE TABLE DocumentFolders (documentId INTEGER, folderId INTEGER);
            INSERT INTO Documents VALUES (1, 'Ciambella2025', '10.5555/hydrogel.2025.001', 'x', 'true', 'false',
                '<p>from db</p>', 'false');
            INSERT INTO Documents VALUES (2, 'Gone2000', NULL, 'deleted', 'true', 'true', NULL, 'true');
            INSERT INTO Folders VALUES (10, 'Thesis', -1), (11, 'Chapter 2', 10);
            INSERT INTO DocumentFolders VALUES (1, 11), (2, 10);
            """
        )
    return path


