# =========================================================================== 4. inbox watcher
def wait_for(predicate: Callable[[], bool], timeout_s: float = 10.0) -> bool:
    deadline = time.monotonic() + timeout_s
    while time.monotonic() < deadline:
        if predicate():
            return True
        time.sleep(0.05)
    return predicate()


@pytest.mark.parametrize("use_watchdog", [False, True])
def test_inbox_watcher_dispatches_complete_pdfs_once(tmp_path: Path, use_watchdog: bool) -> None:
    if use_watchdog:
        pytest.importorskip("watchdog")
    inbox = tmp_path / "inbox"
    seen: list[Path] = []
    lock = threading.Lock()

    def on_ready(path: Path) -> None:
        with lock:
            seen.append(path)

    write_pdf(inbox / "already-there.pdf")
    watcher = InboxWatcher(inbox, on_ready, settle_s=0.3, poll_s=0.1, rescan_s=0.5, use_watchdog=use_watchdog)
    watcher.start()
    try:
        assert watcher.backend == ("watchdog" if use_watchdog else "polling")
        assert wait_for(lambda: [p.name for p in seen] == ["already-there.pdf"])
        (inbox / "download.pdf.crdownload").write_bytes(b"%PDF-1.4 partial")
        (inbox / "notes.txt").write_text("not a pdf")
        (inbox / "Duplicates").mkdir()
        write_pdf(inbox / "Duplicates" / "old.pdf")
        fake = inbox / "fake.pdf"
        fake.write_bytes(b"<html>login page</html>")
        write_pdf(tmp_path / "staging" / "new.pdf")
        (inbox / "sub").mkdir()
        shutil.move(str(tmp_path / "staging" / "new.pdf"), str(inbox / "sub" / "new.pdf"))  # saved "atomically"
        assert wait_for(lambda: len(seen) == 2)
        time.sleep(1.0)
        assert sorted(p.name for p in seen) == ["already-there.pdf", "new.pdf"]  # once each, nothing else
    finally:
        watcher.stop()
    assert not watcher.running


