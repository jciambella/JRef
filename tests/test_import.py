def test_per_file_folders_and_summaries(library: Library, tmp_path: Path) -> None:
    from bibmanager.core.mendeley import folder_name_for, suggest_bib_folder, summarize_bib_file

    entry = "@article{Rossi2021,\nauthor = {Rossi, Mario},\ntitle = {{T}},\nyear = {2021}\n}\n"
    (tmp_path / "Thesis.bib").write_text(entry, encoding="utf-8")
    (tmp_path / "library.bib").write_text(entry + entry.replace("Rossi2021", "Verdi2020"), encoding="utf-8")
    thesis, whole = tmp_path / "Thesis.bib", tmp_path / "library.bib"
    assert suggest_bib_folder(thesis, 2) and not suggest_bib_folder(whole, 2) and not suggest_bib_folder(thesis, 1)
    summary = summarize_bib_file(whole)
    assert (summary.entries, summary.with_groups, summary.with_files) == (2, 0, 0)
    assert summarize_bib_file(tmp_path / "Hydro.bib").error  # unreadable file reported, not raised

    options = MendeleyImportOptions(bib_paths=[thesis, whole], bib_folders={thesis: "PhD  thesis", whole: ""})
    assert (folder_name_for(options, thesis), folder_name_for(options, whole)) == ("PhD thesis", "")
    import_all(library, options)
    rossi = library.db.get_paper_by_citation_key("Rossi2021")
    verdi = library.db.get_paper_by_citation_key("Verdi2020")
    assert rossi is not None and verdi is not None
    assert [c.name for c in library.collections_of(rossi.id)] == ["PhD thesis"]
    assert library.collections_of(verdi.id) == []


def test_reimport_attaches_pdfs_and_folders_to_existing_entries(
    library: Library, mendeley_export: tuple[Path, Path]
) -> None:
    bib, folder = mendeley_export
    import_all(library, MendeleyImportOptions(bib_paths=[bib], pdf_folder=bib.parent, import_groups=False))
    paper = library.db.get_paper_by_citation_key("Ciambella2025")
    assert paper is not None and not paper.has_pdf and library.collections_of(paper.id) == []
    assert library.missing_pdf_hints(paper)[0].endswith("Ciambella et al. - 2025 - Hydrogel fracture.pdf")
    assert "file" not in bib_entries(library.bib.master_path)["Ciambella2025"]  # the hint is never exported

    with library.bulk_update():  # second run, with the right PDF folder and the folders
        statuses = {}
        for cand in plan_import(MendeleyImportOptions(bib_paths=[bib], pdf_folder=folder)).candidates:
            cand = library.prepare_reference(cand)
            ids = [library.ensure_collection_path(p) for p in cand.folders]
            statuses[cand.key] = library.commit_reference(cand, folder_ids=ids)
    assert statuses["Ciambella2025"].attached_pdf and statuses["Smith2020a"].attached_pdf
    paper = library.get_paper(paper.id)
    assert (
        paper.pdf_linked
        and library.pdf_path(paper) == folder / "Hydrogels" / "Ciambella et al. - 2025 - Hydrogel fracture.pdf"
    )
    assert library.missing_pdf_hints(paper) == []
    assert [c.name for c in library.collections_of(paper.id)] == ["Hydrogels", "Thesis"]
    assert [h.paper_id for h in library.search_fulltext("hydrogel")] == [paper.id]


def test_attach_pdf_to_a_reference_without_one(library: Library, tmp_path: Path, make_pdf: Callable[..., Path]) -> None:
    from bibmanager.core import LibraryError, ReferenceCandidate

    ref = ReferenceCandidate("davidovitch:2011", meta("Davidovitch", year=2011, title="Tensional wrinkling"))
    paper = library.commit_reference(ref).paper
    assert not paper.has_pdf and paper.citation_key == "davidovitch:2011"
    pdf = make_pdf("wrinkling.pdf", lines=["tensional wrinkling of thin sheets"])
    attached = library.attach_pdf(paper.id, library.prepare_attachment(pdf), mode="copy")
    assert attached.pdf_managed and attached.citation_key == "davidovitch_2011"  # ':' cannot be in a file name
    assert attached.relative_pdf_path == "pdfs/2011/davidovitch_2011.pdf" and pdf.exists()
    assert "davidovitch_2011" in bib_entries(library.bib.master_path)
    assert [h.paper_id for h in library.search_fulltext("wrinkling sheets")] == [paper.id]
    with pytest.raises(LibraryError, match="already has a PDF"):
        library.attach_pdf(paper.id, library.prepare_attachment(pdf))

    other = library.commit_reference(ReferenceCandidate("Other2020", meta("Other", year=2020))).paper
    with pytest.raises(LibraryError, match="already in the library as davidovitch_2011"):
        library.attach_pdf(other.id, library.prepare_attachment(pdf), mode="link")
    linked = library.attach_pdf(other.id, library.prepare_attachment(make_pdf("other.pdf")), mode="link")
    assert linked.pdf_linked and linked.citation_key == "Other2020"


def test_find_missing_pdfs_rules_and_ties(tmp_path: Path) -> None:
    from bibmanager.core.models import Paper
    from bibmanager.core.relink import find_missing_pdfs

    def paper(pid: int, key: str, title: str, year: int | None, recorded: str = "") -> Paper:
        m = PaperMetadata(title=title, year=year, extra_fields={"file": recorded} if recorded else {})
        return Paper(id=pid, sha256=None, citation_key=key, relative_pdf_path=None, meta=m)

    root = tmp_path / "Mendeley Desktop"
    files = {
        "renamed by hand.pdf": "x",
        "Davidovitch2011.pdf": "x",
        "Bao et al. - 2009 - Controlled ripple texturing of suspended graphene.pdf": "x",  # truncated title
        "Cerda, Mahadevan - 2003 - Geometry and physics.pdf": "x",
        "copy1/Cerda, Mahadevan - 2003 - Geometry and physics.pdf": "x",  # same name twice -> ambiguous
        "notes about surface instability in gradient elasticity 1998.pdf": "x",
        "unrelated.pdf": "x",
    }
    for name in files:
        write_pdf(root / name)
    papers = [
        paper(1, "Gu2013", "Surface effect in the wrinkling of elastic sheet", 2013, "C:/old/renamed by hand.pdf"),
        paper(2, "Davidovitch2011", "Prototypical model for tensional wrinkling", 2011),
        paper(3, "Bao2009", "Controlled ripple texturing of suspended graphene and ultrathin graphite membranes", 2009),
        paper(4, "Cerda2003", "Geometry and physics of wrinkling", 2003),
        paper(5, "Exadaktylos1998", "Surface instability in gradient elasticity with surface energy", 1998),
        paper(6, "Nobody2000", "Not on disk", 2000),
    ]
    result = find_missing_pdfs(papers, [root], exclude=[root / "unrelated.pdf"])
    found = {m.paper_id: (m.path.name, m.rule) for m in result.matches}
    assert found == {
        1: ("renamed by hand.pdf", "recorded"),
        2: ("Davidovitch2011.pdf", "key"),
        3: ("Bao et al. - 2009 - Controlled ripple texturing of suspended graphene.pdf", "title"),
        5: ("notes about surface instability in gradient elasticity 1998.pdf", "fuzzy"),
    }
    assert [pid for pid, _ in result.ambiguous] == [4]
    assert (result.scanned, result.searched) == (6, 6)
